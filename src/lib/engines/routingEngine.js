import { NetworkValidationError } from '../errors/NetworkErrors';

/**
 * Routing Protocol Decision Engine
 * Deterministic recommendation engine based on subnet count, site topology, routing domains, and cloud connectivity.
 */
export function recommendRouting(params = {}) {
  const {
    subnetsCount = 1,
    sitesCount = 1,
    networkType = 'Campus LAN', // 'Campus LAN', 'Metro MAN', 'Global WAN', 'Custom'
    cloudIntegration = false,
    externalAsRequired = false,
    autonomousSystemNumber = 65001,
    remoteOfficesCount = 0,
    hasRedundantPaths = true
  } = params;

  if (subnetsCount < 1 || isNaN(Number(subnetsCount))) {
    throw new NetworkValidationError('Subnets count must be a positive integer.', 'subnetsCount', subnetsCount);
  }

  const isMultiSite = sitesCount > 1 || remoteOfficesCount > 0;
  const isLargeSubnetScale = subnetsCount >= 50;

  let protocol = '';
  let architecture = '';
  let rfcReferences = [];
  let technicalExplanation = '';
  let convergenceNotes = '';
  let summarizationPlan = '';
  let alternativesRejected = [];
  let areaDesign = [];

  if (!isMultiSite && !cloudIntegration && !isLargeSubnetScale) {
    // Single Autonomous System with fewer than 50 subnets: OSPF Area 0
    protocol = 'Single-Area OSPF (Open Shortest Path First v2 - Area 0)';
    architecture = 'Interior Gateway Protocol (IGP) - Single Backbone Area';
    rfcReferences = [
      'RFC 2328: OSPF Version 2 (STD 54)',
      'RFC 3101: The OSPF Not-So-Stubby Area (NSSA) Option',
      'RFC 5340: OSPF for IPv6 (OSPFv3)'
    ];
    technicalExplanation =
      `For a single autonomous system with ${subnetsCount} subnets (fewer than 50 threshold), Single-Area OSPF (Backbone Area 0) is optimal. ` +
      `OSPF uses Dijkstra's Shortest Path First (SPF) algorithm to calculate loop-free paths with rapid sub-second convergence. ` +
      `Because the Link-State Database (LSDB) remains compact under 50 subnets, CPU and memory overhead during SPF recalculations is negligible, ` +
      `obviating the configuration complexity of multi-area partitioning.`;

    convergenceNotes =
      'Sub-second failure detection via OSPF Hello/Dead intervals (10s/40s standard, or fast hellos/BFD for sub-50ms convergence) ' +
      'with immediate Link State Advertisement (LSA) flooding on link state changes.';

    summarizationPlan =
      'Route summarization is not required inside a single area because all OSPF routers maintain identical LSDBs; ' +
      'summarization occurs at Area Border Routers (ABRs) or Autonomous System Boundary Routers (ASBRs).';

    areaDesign = [
      { area: '0.0.0.0 (Area 0)', role: 'Backbone Area', description: 'Core and distribution switches participate in single backbone link-state graph.' }
    ];

    alternativesRejected = [
      {
        protocol: 'EIGRP (Enhanced Interior Gateway Routing Protocol)',
        reason: 'Cisco-proprietary lineage (RFC 7868 informational); lacks open multi-vendor interoperability and standardization guarantees.'
      },
      {
        protocol: 'RIPv2 (Routing Information Protocol)',
        reason: 'Distance-vector protocol with 15-hop limit, slow timer-based convergence (up to 180 seconds), and high bandwidth consumption due to periodic broadcast/multicast updates (RFC 2453).'
      },
      {
        protocol: 'BGP (Border Gateway Protocol)',
        reason: 'Heavy path-vector protocol with extensive memory requirements and slower convergence; excessive operational complexity for an internal single-site LAN.'
      }
    ];
  } else if ((isMultiSite || isLargeSubnetScale) && !cloudIntegration && !externalAsRequired) {
    // Multi-site enterprise or >= 50 subnets in single enterprise: Multi-Area OSPF
    protocol = 'Multi-Area OSPF (Hierarchical Link-State)';
    architecture = 'Interior Gateway Protocol (IGP) - Area 0 Backbone with Regional Areas';
    rfcReferences = [
      'RFC 2328: OSPF Version 2',
      'RFC 3509: Alternative Implementations of OSPF Area Border Routers',
      'RFC 1583: OSPF Version 2'
    ];
    technicalExplanation =
      `With ${sitesCount} sites and ${subnetsCount} subnets, a hierarchical multi-area OSPF design is mandated. ` +
      `Area 0 (Backbone) interconnects all Area Border Routers (ABRs). Each regional site is assigned a dedicated non-backbone area (e.g. Area 10, Area 20). ` +
      `This confines Type 1 and Type 2 LSA flooding and Dijkstra SPF calculations strictly within the originating area, ` +
      `isolating route churn and preserving router processing resources.`;

    convergenceNotes =
      'Link flapping within one campus site only triggers SPF execution within its local area; ' +
      'other sites receive stable Type 3 Summary LSAs generated by the ABR.';

    summarizationPlan =
      'ABRs perform contiguous inter-area route summarization (e.g., using `area X range` Cisco IOS statements), ' +
      'collapsing dozens of departmental subnets into single summary prefixes announced into Area 0.';

    areaDesign = [
      { area: '0.0.0.0 (Area 0)', role: 'Core Backbone', description: 'Interconnects core distribution layer and WAN routers.' },
      { area: '0.0.0.10 (Area 10)', role: 'Headquarters / Main Campus', description: 'Local user and server access subnets.' },
      { area: '0.0.0.20 (Area 20)', role: 'Remote Site 1 / Colocation', description: 'Regional branch or datacenter subnets.' },
      { area: '0.0.0.30 (Area 30)', role: 'Remote Site 2 / Secondary Site', description: 'Regional branch subnets.' }
    ];

    alternativesRejected = [
      {
        protocol: 'Single-Area OSPF Flat Topology',
        reason: 'A flat Area 0 across multi-site links propagates every link flap globally, causing repeated full SPF tree recalculations across all routers.'
      },
      {
        protocol: 'Static Routing with Floating Backup',
        reason: 'Unmaintainable at this scale; does not automatically adapt to link degradation or dynamic topology changes.'
      }
    ];
  } else {
    // Global WAN or Cloud Integration: Hybrid Architecture (OSPF IGP + eBGP / IPsec VPN)
    protocol = 'Hybrid Routing: Multi-Area OSPF (IGP) + External BGP (eBGP / IPsec WAN)';
    architecture = 'Dual-Tier: Internal Link-State IGP (OSPF) + Inter-Domain Path-Vector (BGP-4 / RFC 4271)';
    rfcReferences = [
      'RFC 4271: A Border Gateway Protocol 4 (BGP-4)',
      'RFC 2328: OSPF Version 2',
      'RFC 4364: BGP/MPLS IP Virtual Private Networks (VPNs)',
      'RFC 4301: Security Architecture for the Internet Protocol (IPsec)'
    ];
    technicalExplanation =
      `For multi-site global WAN infrastructure with ${sitesCount} sites and Cloud VPC integration, a hybrid routing architecture is required. ` +
      `Internal site networks utilize Multi-Area OSPF for fast IGP convergence. Edge routers and Cloud Virtual Private Gateways run eBGP (AS ${autonomousSystemNumber} to Cloud AS 64512), ` +
      `enabling policy-based path control, AS_PATH loop prevention, multi-exit discriminators (MED), and controlled route redistribution at ASBR boundaries.`;

    convergenceNotes =
      'OSPF handles millisecond internal rerouting; BGP with BFD (Bidirectional Forwarding Detection) provides 300ms failover across redundant WAN circuits and cloud tunnels.';

    summarizationPlan =
      'Autonomous System Boundary Routers (ASBRs) announce only aggregated supernet CIDR blocks to cloud peers and service providers, ' +
      'strictly filtering internal RFC 1918 departmental subnets from leaking onto untrusted transit links.';

    areaDesign = [
      { area: 'Area 0 (Backbone)', role: 'Enterprise Core & WAN Edge', description: 'Transits internal traffic between sites and data centers.' },
      { area: 'eBGP Peering', role: 'Cloud VPC & Carrier EVPL Border', description: 'Autonomous System peering with AWS Direct Connect / Azure ExpressRoute and Cloud VPC.' }
    ];

    alternativesRejected = [
      {
        protocol: 'Pure OSPF over Global Internet/Cloud',
        reason: 'OSPF cannot cross independent administrative boundaries, cannot enforce multi-hop AS path policy filters, and exposes internal link states to third-party cloud providers.'
      },
      {
        protocol: 'Pure BGP for all internal desktop subnets',
        reason: 'BGP lacks rapid link-state discovery and topology awareness necessary for high-density local campus switching and fast convergence.'
      }
    ];
  }

  return {
    protocol,
    architecture,
    rfcReferences,
    technicalExplanation,
    convergenceNotes,
    summarizationPlan,
    areaDesign,
    alternativesRejected,
    parametersAnalyzed: {
      subnetsCount,
      sitesCount,
      networkType,
      cloudIntegration,
      externalAsRequired
    }
  };
}
