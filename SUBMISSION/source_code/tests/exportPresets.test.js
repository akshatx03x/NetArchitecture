import fs from 'fs';
import path from 'path';
import { planNetwork } from '../src/lib/engines/networkEngine';
import { campusLANPreset } from '../src/lib/presets/campusLAN';
import { metroMANPreset } from '../src/lib/presets/metroMAN';
import { globalWANPreset } from '../src/lib/presets/globalWAN';

describe('Generate Presets Submission Exports', () => {
  test('generates all submission artifacts for Campus LAN, Metro MAN, and Global WAN', () => {
    const rootDir = path.resolve(__dirname, '..');

    const presets = [
      { preset: campusLANPreset, folder: 'profile-1-campus-lan', submissionCfg: 'campus_lan.cfg' },
      { preset: metroMANPreset, folder: 'profile-2-metro-man', submissionCfg: 'metro_man.cfg' },
      { preset: globalWANPreset, folder: 'profile-3-global-wan', submissionCfg: 'global_wan.cfg' }
    ];

    const submissionExportDir = path.join(rootDir, 'SUBMISSION', 'configuration_exports');
    fs.mkdirSync(submissionExportDir, { recursive: true });

    presets.forEach(({ preset, folder, submissionCfg }) => {
      const result = planNetwork(preset);
      const outDir = path.join(rootDir, 'exports', folder);
      fs.mkdirSync(outDir, { recursive: true });

      // 1. Write Cisco Configurations to exports/
      const configs = result.configurations;
      fs.writeFileSync(path.join(outDir, configs.coreSwitch.filename), configs.coreSwitch.content, 'utf8');
      fs.writeFileSync(path.join(outDir, configs.accessSwitch.filename), configs.accessSwitch.content, 'utf8');
      fs.writeFileSync(path.join(outDir, configs.edgeRouter.filename), configs.edgeRouter.content, 'utf8');
      fs.writeFileSync(path.join(outDir, configs.securityAcl.filename), configs.securityAcl.content, 'utf8');

      // 2. Write Consolidated Cisco Configuration to SUBMISSION/configuration_exports/
      let consolidated = '';
      consolidated += `! =====================================================================\n`;
      consolidated += `! NetArchitect Production Cisco Configuration Package\n`;
      consolidated += `! Scenario: ${preset.name} (${preset.networkType})\n`;
      consolidated += `! Course: CIC-307 Computer Networks Mini-Project\n`;
      consolidated += `! Target Platform: Cisco Catalyst 9000 & Cisco ISR 4000 (IOS-XE 17.x)\n`;
      consolidated += `! Generated by NetArchitect Deterministic Decision Engine\n`;
      consolidated += `! =====================================================================\n\n`;

      consolidated += `! #####################################################################\n`;
      consolidated += `! SECTION 1: CORE / DISTRIBUTION MULTILAYER SWITCH (CORE-SW01)\n`;
      consolidated += `! File: ${configs.coreSwitch.filename}\n`;
      consolidated += `! Description: Rapid-PVST+ Root, SVI Routing, 802.1Q Trunks, Dynamic Routing\n`;
      consolidated += `! #####################################################################\n\n`;
      consolidated += configs.coreSwitch.content + `\n\n`;

      consolidated += `! #####################################################################\n`;
      consolidated += `! SECTION 2: LAYER 2 ACCESS SWITCH (ACC-SW01)\n`;
      consolidated += `! File: ${configs.accessSwitch.filename}\n`;
      consolidated += `! Description: Access Ports, PortFast, BPDU Guard, Trunk Uplinks\n`;
      consolidated += `! #####################################################################\n\n`;
      consolidated += configs.accessSwitch.content + `\n\n`;

      consolidated += `! #####################################################################\n`;
      consolidated += `! SECTION 3: BORDER / EDGE ROUTER (EDGE-RTR01)\n`;
      consolidated += `! File: ${configs.edgeRouter.filename}\n`;
      consolidated += `! Description: WAN / Cloud Uplinks, /30 Point-to-Point Links, Routing\n`;
      consolidated += `! #####################################################################\n\n`;
      consolidated += configs.edgeRouter.content + `\n\n`;

      consolidated += `! #####################################################################\n`;
      consolidated += `! SECTION 4: SECURITY ACCESS CONTROL LIST POLICY (SECURITY-ACLS)\n`;
      consolidated += `! File: ${configs.securityAcl.filename}\n`;
      consolidated += `! Description: Extended Named ACLs, Inter-VLAN Traffic Isolation\n`;
      consolidated += `! #####################################################################\n\n`;
      consolidated += configs.securityAcl.content + `\n\n`;

      fs.writeFileSync(path.join(submissionExportDir, submissionCfg), consolidated, 'utf8');

      // 3. Write VLSM CSV
      let csv = 'Name,VLAN ID,Requested Hosts,CIDR,Network Address,Subnet Mask,Wildcard Mask,First Usable,Last Usable,Broadcast,Default Gateway,Usable Capacity,Utilization %\n';
      result.vlsm.allocatedSubnets.forEach(s => {
        csv += `"${s.name}",${s.vlanId},${s.requestedHosts},"${s.cidr}","${s.networkAddress}","${s.subnetMask}","${s.wildcardMask}","${s.firstUsable}","${s.lastUsable}","${s.broadcastAddress}","${s.defaultGateway}",${s.usableHosts},${s.utilizationPercent}%\n`;
      });
      fs.writeFileSync(path.join(outDir, `${folder}_VLSM_Subnets.csv`), csv, 'utf8');

      // 4. Write Architectural Decision Record Markdown
      fs.writeFileSync(path.join(outDir, `${folder}_Architectural_Decisions.md`), result.rawExplanations.exportMarkdown(), 'utf8');

      // 5. Write full scenario export JSON
      fs.writeFileSync(path.join(outDir, `${folder}_Architecture_Export.json`), JSON.stringify(result, null, 2), 'utf8');

      // Assertions to verify generation succeeded
      expect(fs.existsSync(path.join(outDir, configs.coreSwitch.filename))).toBe(true);
      expect(fs.existsSync(path.join(outDir, `${folder}_VLSM_Subnets.csv`))).toBe(true);
      expect(fs.existsSync(path.join(outDir, `${folder}_Architectural_Decisions.md`))).toBe(true);
      expect(fs.existsSync(path.join(submissionExportDir, submissionCfg))).toBe(true);
    });
  });
});
